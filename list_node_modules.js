const fs = require('fs');
const path = require('path');

const targetDir = path.resolve(__dirname, '../../workforce-semantic-layer/node_modules');
if (fs.existsSync(targetDir)) {
  console.log('Contents of node_modules:');
  fs.readdirSync(targetDir).forEach(f => {
    if (f.startsWith('@cubejs-backend')) {
      console.log(`  ${f}:`);
      fs.readdirSync(path.join(targetDir, f)).forEach(sf => {
        console.log(`    - ${sf}`);
      });
    } else if (f.includes('cubejs') || f.includes('hana')) {
      console.log(`  ${f}`);
    }
  });
} else {
  console.log('node_modules directory not found at:', targetDir);
}
